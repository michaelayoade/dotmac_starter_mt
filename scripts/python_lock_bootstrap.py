#!/usr/bin/env python3
"""Generate an unqualified Poetry lock proposal on same-repository hosted PR CI.

Reviewed metadata/source bytes are applied only to a temporary copy of a clean
committed checkout. This producer installs no product dependencies, runs no
product code/tests, and never commits, pushes, publishes or qualifies its output.
The owner must integrate the generated lock and proposed metadata together.
"""

