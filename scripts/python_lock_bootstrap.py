#!/usr/bin/env python3
"""Generate an unqualified Poetry lock proposal on same-repository hosted PR CI.

Reviewed metadata/source bytes are applied only to a temporary copy of a clean
committed checkout. This producer installs no product dependencies, runs no
product code/tests, and never commits, pushes, publishes or qualifies its output.
The owner must integrate the generated lock and proposed metadata together.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
from dataclasses import asdict, dataclass
from pathlib import Path, PurePosixPath
from typing import Literal, cast

PROPOSAL_PATH = "docs/inventories/python-lock-bootstrap/learning.json"
OUTPUT_PATH = "python-lock-bootstrap-artifact"
PACKAGE_PATH = "packages/dotmac-learning/"
SOURCE_PATH = PACKAGE_PATH + "src/dotmac_learning/"
METADATA_PATHS = frozenset({"pyproject.toml", PACKAGE_PATH + "pyproject.toml"})
REQUIRED_SOURCES = frozenset(
    {SOURCE_PATH + "__init__.py", SOURCE_PATH + "py.typed", PACKAGE_PATH + "README.md"}
)
_HEX40 = re.compile(r"[0-9a-f]{40}")
_HEX64 = re.compile(r"[0-9a-f]{64}")
_VERSION = re.compile(r"[0-9]+(?:\.[0-9]+){2}(?:[A-Za-z0-9.-]+)?")
_BOOTSTRAP_PIN = re.compile(r"^poetry==([^\s\\]+)(?:\s+\\)?$", re.MULTILINE)
_LOCK_HEADER = re.compile(
    r"^# This file is automatically @generated by Poetry ([^ ]+) "
    r"and should not be changed by hand\.$"
)


class BootstrapError(ValueError):
    """Payload-free refusal; command output and proposed contents are never shown."""


@dataclass(frozen=True, slots=True, repr=False)
class ProposedFile:
    path: str
    before_sha256: str | None
    content: str
    sha256: str


@dataclass(frozen=True, slots=True, repr=False)
class Proposal:
    schema_version: Literal[1]
    base_sha: str
    package: Literal["dotmac-learning"]
    files: tuple[ProposedFile, ...]
    package_sources: tuple[ProposedFile, ...]


@dataclass(frozen=True, slots=True)
class HostedContext:
    checkout_sha: str
    pull_request_head_sha: str


@dataclass(frozen=True, slots=True)
class CheckoutObservation:
    checkout_sha: str
    parent_shas: tuple[str, ...]
    tracked_paths: tuple[str, ...]
    poetry_version: str
    original_lock_sha256: str


@dataclass(frozen=True, slots=True)
class ProposedFileHash:
    path: str
    before_sha256: str | None
    sha256: str


@dataclass(frozen=True, slots=True)
class LockGenerationManifest:
    schema_version: Literal[1]
    purpose: Literal["generated_unqualified_lock"]
    package: Literal["dotmac-learning"]
    base_sha: str
    checkout_sha: str
    parent_shas: tuple[str, ...]
    input_sha256: str
    proposed_files: tuple[ProposedFileHash, ...]
    poetry_version: str
    original_lock_sha256: str
    lock_sha256: str


def _digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _pairs(pairs: list[tuple[str, object]]) -> dict[str, object]:
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise BootstrapError("duplicate JSON object key")
        result[key] = value
    return result


def _object(value: object, keys: frozenset[str]) -> dict[str, object]:
    if not isinstance(value, dict) or set(value) != keys:
        raise BootstrapError("proposal object has missing or extra fields")
    return cast(dict[str, object], value)


def _relative_path(value: object) -> str:
    if not isinstance(value, str) or not value or "\\" in value or "\0" in value:
        raise BootstrapError("invalid relative path")
    path = PurePosixPath(value)
    if (
        path.is_absolute()
        or path.as_posix() != value
        or any(part in {"..", ".", ".git"} for part in path.parts)
    ):
        raise BootstrapError("invalid relative path")
    return value


def _file(value: object) -> ProposedFile:
    item = _object(value, frozenset({"path", "before_sha256", "content", "sha256"}))
    path = _relative_path(item["path"])
    before, content, digest = item["before_sha256"], item["content"], item["sha256"]
    if before is not None and (
        not isinstance(before, str) or not _HEX64.fullmatch(before)
    ):
        raise BootstrapError("invalid prior file digest")
    if (
        not isinstance(content, str)
        or not isinstance(digest, str)
        or not _HEX64.fullmatch(digest)
    ):
        raise BootstrapError("invalid proposed file content or digest")
    try:
        actual = _digest(content.encode("utf-8"))
    except UnicodeEncodeError:
        raise BootstrapError("proposed content is not UTF-8") from None
    if actual != digest:
        raise BootstrapError("proposed file digest mismatch")
    return ProposedFile(path, before, content, digest)


def parse_proposal(raw: bytes) -> Proposal:
    """Parse only the closed reviewed two-metadata-file and learning-source schema."""
    try:
        decoded: object = json.loads(raw, object_pairs_hook=_pairs)
    except (ValueError, UnicodeDecodeError):
        raise BootstrapError("invalid proposal JSON") from None
    item = _object(
        decoded,
        frozenset(
            {"schema_version", "base_sha", "package", "files", "package_sources"}
        ),
    )
    if type(item["schema_version"]) is not int or item["schema_version"] != 1:
        raise BootstrapError("unsupported proposal schema")
    base = item["base_sha"]
    if not isinstance(base, str) or not _HEX40.fullmatch(base):
        raise BootstrapError("immutable proposal base SHA required")
    if item["package"] != "dotmac-learning":
        raise BootstrapError("unsupported proposal package")
    metadata, sources = item["files"], item["package_sources"]
    if not isinstance(metadata, list) or not isinstance(sources, list) or not sources:
        raise BootstrapError("explicit metadata and nonempty source arrays required")
    files = tuple(_file(value) for value in metadata)
    package_sources = tuple(_file(value) for value in sources)
    paths = [file.path for file in files + package_sources]
    if len(set(paths)) != len(paths):
        raise BootstrapError("duplicate proposed path")
    if any(
        parent.as_posix() in paths
        for path in paths
        for parent in PurePosixPath(path).parents
    ):
        raise BootstrapError("proposed file paths overlap")
    if {file.path for file in files} != METADATA_PATHS:
        raise BootstrapError("exactly the two reviewed metadata targets are required")
    for file in files + package_sources:
        if (file.path == "pyproject.toml") != (file.before_sha256 is not None):
            raise BootstrapError(
                "only the existing root metadata requires a prior digest"
            )
    source_paths = {file.path for file in package_sources}
    if not REQUIRED_SOURCES <= source_paths:
        raise BootstrapError(
            "reviewed package initializer, typing marker and README required"
        )
    if any(
        not (path.startswith(SOURCE_PATH) or path == PACKAGE_PATH + "README.md")
        for path in source_paths
    ):
        raise BootstrapError("source path outside the closed learning extent")
    return Proposal(1, base, "dotmac-learning", files, package_sources)


def _no_symlinks(root: Path, relative: str) -> Path:
    path = root
    for part in PurePosixPath(relative).parts:
        path = path / part
        if path.is_symlink():
            raise BootstrapError("symlink path refused")
    return path


def _read(root: Path, relative: str) -> bytes:
    path = _no_symlinks(root, relative)
    if not path.is_file():
        raise BootstrapError("required regular file absent")
    return path.read_bytes()


def _command(arguments: tuple[str, ...], cwd: Path, *, capture_stdout: bool) -> bytes:
    try:
        result = subprocess.run(
            arguments,
            cwd=cwd,
            env={**os.environ, "GIT_NO_LAZY_FETCH": "1", "GIT_TERMINAL_PROMPT": "0"},
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE if capture_stdout else subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            shell=False,
            check=False,
            timeout=1200,
        )
    except (OSError, subprocess.TimeoutExpired):
        raise BootstrapError(
            "hosted producer command unavailable or timed out"
        ) from None
    if result.returncode != 0:
        raise BootstrapError("hosted producer command refused")
    if not capture_stdout:
        return b""
    if not isinstance(result.stdout, bytes):
        raise BootstrapError("hosted command output unavailable")
    return result.stdout


def _git(repo: Path, arguments: tuple[str, ...]) -> bytes:
    return _command(("git", *arguments), repo, capture_stdout=True)


def _require_hosted(repo: Path) -> HostedContext:
    if (
        os.environ.get("GITHUB_ACTIONS") != "true"
        or os.environ.get("RUNNER_ENVIRONMENT") != "github-hosted"
        or os.environ.get("GITHUB_EVENT_NAME") != "pull_request"
        or Path(os.environ.get("GITHUB_WORKSPACE", "")).resolve() != repo.resolve()
    ):
        raise BootstrapError("same-repository Git-hosted PR context required")
    sha = os.environ.get("GITHUB_SHA", "")
    repository = os.environ.get("GITHUB_REPOSITORY", "")
    if not _HEX40.fullmatch(sha) or not repository:
        raise BootstrapError("immutable hosted checkout identity required")
    try:
        event: object = json.loads(Path(os.environ["GITHUB_EVENT_PATH"]).read_bytes())
        if not isinstance(event, dict):
            raise BootstrapError("invalid hosted event")
        pull_request = event["pull_request"]
        head = pull_request["head"]
        if (
            head["repo"]["full_name"] != repository
            or pull_request["base"]["repo"]["full_name"] != repository
        ):
            raise BootstrapError("fork proposal refused")
        head_sha = head["sha"]
        if not isinstance(head_sha, str) or not _HEX40.fullmatch(head_sha):
            raise BootstrapError("immutable PR head required")
    except (KeyError, TypeError, OSError, ValueError):
        raise BootstrapError("same-repository hosted event required") from None
    return HostedContext(sha, head_sha)


def _poetry_pin(content: bytes) -> str:
    try:
        value = tomllib.loads(content.decode("utf-8"))["tool"]["poetry"][
            "requires-poetry"
        ]
    except (KeyError, TypeError, ValueError):
        raise BootstrapError("exact root Poetry pin required") from None
    if not isinstance(value, str) or not _VERSION.fullmatch(value):
        raise BootstrapError("exact root Poetry pin required")
    return value


def _lock_version(content: bytes) -> str:
    try:
        lines = content.decode("utf-8").splitlines()
    except UnicodeDecodeError:
        raise BootstrapError("invalid lock generator stamp") from None
    match = _LOCK_HEADER.fullmatch(lines[0] if lines else "")
    if match is None:
        raise BootstrapError("invalid lock generator stamp")
    return match.group(1)


def validate_checkout(
    repo: Path, proposal: Proposal, context: HostedContext
) -> CheckoutObservation:
    """Bind every proposed byte to a clean immutable checkout and ancestor base."""
    # Revalidate even if a caller constructed/replaced dataclasses directly.
    proposal = parse_proposal(json.dumps(asdict(proposal), ensure_ascii=True).encode())
    checkout = _git(repo, ("rev-parse", "--verify", "HEAD")).decode().strip()
    if checkout != context.checkout_sha or not _HEX40.fullmatch(checkout):
        raise BootstrapError("hosted checkout SHA mismatch")
    _git(repo, ("merge-base", "--is-ancestor", proposal.base_sha, checkout))
    _git(repo, ("merge-base", "--is-ancestor", context.pull_request_head_sha, checkout))
    _git(repo, ("diff", "--quiet", "HEAD", "--"))
    parents = _git(repo, ("rev-list", "--parents", "-n", "1", "HEAD")).decode().split()
    if (
        not parents
        or parents[0] != checkout
        or any(not _HEX40.fullmatch(sha) for sha in parents)
    ):
        raise BootstrapError("checkout parent identities unavailable")
    root = next(file for file in proposal.files if file.path == "pyproject.toml")
    original = _read(repo, "pyproject.toml")
    if any(
        _digest(content) != root.before_sha256
        for content in (
            original,
            _git(repo, ("show", "HEAD:pyproject.toml")),
            _git(repo, ("show", proposal.base_sha + ":pyproject.toml")),
        )
    ):
        raise BootstrapError("base, committed and working root metadata must agree")
    for file in proposal.files + proposal.package_sources:
        target = _no_symlinks(repo, file.path)
        if file.before_sha256 is None and target.exists():
            raise BootstrapError("proposed new target already exists")
    wanted = _poetry_pin(original)
    if _poetry_pin(root.content.encode()) != wanted:
        raise BootstrapError("proposal cannot change the pinned Poetry toolchain")
    try:
        package_file = next(
            file for file in proposal.files if file.path != "pyproject.toml"
        )
        package_name = tomllib.loads(package_file.content)["tool"]["poetry"]["name"]
    except (KeyError, TypeError, ValueError):
        raise BootstrapError("invalid package metadata") from None
    if package_name != "dotmac-learning":
        raise BootstrapError("package metadata name mismatch")
    try:
        requirements = _read(
            repo, ".github/bootstrap/poetry-requirements-py312.txt"
        ).decode()
    except UnicodeDecodeError:
        raise BootstrapError("invalid Poetry bootstrap requirements") from None
    if _BOOTSTRAP_PIN.findall(requirements) != [wanted]:
        raise BootstrapError("hash-locked bootstrap Poetry pin mismatch")
    original_lock = _read(repo, "poetry.lock")
    if _lock_version(original_lock) != wanted:
        raise BootstrapError("committed lock generator pin mismatch")
    tracked_raw = _git(repo, ("ls-files", "-z", "--cached"))
    try:
        tracked = tuple(
            _relative_path(path) for path in tracked_raw.decode().split("\0") if path
        )
    except UnicodeDecodeError:
        raise BootstrapError("tracked source paths unavailable") from None
    if not tracked or len(tracked) != len(set(tracked)):
        raise BootstrapError("tracked source extent unavailable")
    for path in tracked:
        _read(repo, path)
    return CheckoutObservation(
        checkout, tuple(parents[1:]), tracked, wanted, _digest(original_lock)
    )


def produce_lock(
    repo: Path, proposal_path: Path, output: Path
) -> LockGenerationManifest:
    """Generate only an unqualified lock and source-bound manifest in hosted CI."""
    repo = repo.resolve()
    context = _require_hosted(repo)
    try:
        relative = _relative_path(proposal_path.absolute().relative_to(repo).as_posix())
    except ValueError:
        raise BootstrapError("proposal must be inside the checkout") from None
    raw = _read(repo, relative)
    proposal = parse_proposal(raw)
    observed = validate_checkout(repo, proposal, context)
    if output.exists() or output.is_symlink():
        raise BootstrapError("artifact destination must be new")
    version = _command(("poetry", "--version"), repo, capture_stdout=True)
    if version.strip() != f"Poetry (version {observed.poetry_version})".encode():
        raise BootstrapError("active Poetry pin mismatch")
    with tempfile.TemporaryDirectory(prefix="python-lock-bootstrap-") as directory:
        transient = Path(directory) / "checkout"
        transient.mkdir()
        for relative in observed.tracked_paths:
            destination = transient / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(_no_symlinks(repo, relative), destination)
        for file in proposal.files + proposal.package_sources:
            destination = transient / file.path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(file.content.encode("utf-8"))
        _command(
            ("poetry", "lock", "--no-interaction"), transient, capture_stdout=False
        )
        lock = _read(transient, "poetry.lock")
        if _lock_version(lock) != observed.poetry_version:
            raise BootstrapError("generated lock Poetry stamp mismatch")
        for file in proposal.files + proposal.package_sources:
            if _digest(_read(transient, file.path)) != file.sha256:
                raise BootstrapError("lock generation changed proposed source bytes")
    manifest = LockGenerationManifest(
        1,
        "generated_unqualified_lock",
        "dotmac-learning",
        proposal.base_sha,
        observed.checkout_sha,
        observed.parent_shas,
        _digest(raw),
        tuple(
            ProposedFileHash(file.path, file.before_sha256, file.sha256)
            for file in proposal.files + proposal.package_sources
        ),
        observed.poetry_version,
        observed.original_lock_sha256,
        _digest(lock),
    )
    output.mkdir()
    (output / "poetry.lock").write_bytes(lock)
    (output / "manifest.json").write_text(
        json.dumps(asdict(manifest), sort_keys=True, indent=2) + "\n", encoding="utf-8"
    )
    return manifest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--validate", action="store_true")
    arguments = parser.parse_args()
    repo = Path.cwd().resolve()
    proposal_path = repo / PROPOSAL_PATH
    if arguments.validate:
        context = _require_hosted(repo)
        proposal = parse_proposal(_read(repo, PROPOSAL_PATH))
        validate_checkout(repo, proposal, context)
        print("Reviewed lock proposal inputs validated; no qualification asserted.")
    else:
        produce_lock(repo, proposal_path, repo / OUTPUT_PATH)
        print("Unqualified Poetry lock proposal artifact generated for review.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BootstrapError as error:
        print(f"error: {error}", file=sys.stderr)
        raise SystemExit(1) from None
    except OSError:
        print("error: input or artifact filesystem operation failed", file=sys.stderr)
        raise SystemExit(1) from None
