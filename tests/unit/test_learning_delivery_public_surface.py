def test_delivery_read_and_transfer_exports_have_one_original_owner():
    assert len(learning.__all__) == len(set(learning.__all__))
    for public, module, source in PUBLIC_OWNERS:
        assert public in learning.__all__
        owner = importlib.import_module(f"dotmac_learning.{module}")
        assert getattr(learning, public) is getattr(owner, source)


def test_v5_keeps_all_prior_transfer_versions_bound_to_their_owners():
    for version, module in (
        (1, "transfer"),
        (2, "curriculum_transfer"),
        (3, "participation_transfer"),
        (4, "assessment_transfer"),
        (5, "delivery_transfer"),
    ):
        owner = importlib.import_module(f"dotmac_learning.{module}")
        suffix = "" if version == 1 else f"_v{version}"
        for operation in ("export_snapshot", "import_snapshot", "verify_snapshot"):
            name = operation + suffix
            assert getattr(learning, name) is getattr(owner, name)
