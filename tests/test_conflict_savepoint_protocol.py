"""Real PostgreSQL root transaction and transaction-local GUC preservation."""

from uuid import uuid4

import pytest
from dotmac_kernel.models import Role
from dotmac_kernel.transactions import (
    ConflictSavepointPhase,
    ConflictSavepointProtocolError,
    claim_conflict_savepoint_commit,
    conflict_savepoint,
    conflict_savepoint_requires_rollback,
    current_conflict_savepoint,
)
from sqlalchemy import delete, event, func, select, text
from sqlalchemy.exc import IntegrityError, SQLAlchemyError
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    pass


class Item(Base):
    __tablename__ = "kernel_conflict_protocol_item"
    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str] = mapped_column(unique=True)


@pytest.mark.parametrize("explicit_flush", [True, False])
def test_real_postgres_conflict_preserves_root_and_local_tenant(
    admin_session, explicit_flush
):
    db = admin_session
    db.execute(
        text(
            "CREATE TEMPORARY TABLE kernel_conflict_protocol_item "
            "(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "name text NOT NULL UNIQUE) ON COMMIT DROP"
        )
    )
    tenant = str(uuid4())
    db.execute(
        text("SELECT set_config('app.current_tenant', :tenant, true)"),
        {"tenant": tenant},
    )
    db.add(Item(name="duplicate"))
    db.flush()
    root = db.get_transaction()

    def guard(current):
        if not claim_conflict_savepoint_commit(current, expected_root=root):
            raise AssertionError("participant cannot complete owner's transaction")

    event.listen(db, "before_commit", guard)
    try:
        with pytest.raises(IntegrityError), conflict_savepoint(db):
            db.add(Item(name="duplicate"))
            if explicit_flush:
                db.flush()
        assert db.get_transaction() is root and root.is_active
        assert db.is_active and not db.in_nested_transaction()
        assert not conflict_savepoint_requires_rollback(db, expected_root=root)
        assert current_conflict_savepoint(db) is None
        assert not claim_conflict_savepoint_commit(db, expected_root=root)
        assert db.scalar(text("SELECT current_setting('app.current_tenant')")) == tenant
        with conflict_savepoint(db):
            db.add(Item(name="after-conflict"))
            db.flush()
        assert db.get_transaction() is root
        assert (
            db.scalar(text("SELECT count(*) FROM kernel_conflict_protocol_item")) == 2
        )
    finally:
        event.remove(db, "before_commit", guard)


@pytest.mark.parametrize("event_name", ["before_commit", "before_flush"])
@pytest.mark.parametrize("listener_first", [True, False])
@pytest.mark.parametrize("root_direct", [True, False])
@pytest.mark.parametrize("swallow", [True, False])
def test_real_postgres_reentrant_completion_never_publishes_before_owner_boundary(
    admin_session,
    admin_engine,
    tenant_a,
    event_name,
    listener_first,
    root_direct,
    swallow,
):
    """An independent connection proves no writer commit escaped the owner.

    Use the existing persistent roles table: temporary tables cannot provide
    this visibility proof. The unique row is explicitly cleaned even if the
    planted defect were to commit it, in addition to tenant fixture cleanup.
    """
    db = admin_session
    tenant_id = tenant_a.id
    row_id = uuid4()
    db.connection()
    root = db.get_transaction()
    attempts = []
    denied = []
    completion_errors = []

    def observe_count():
        with admin_engine.connect() as observer:
            return observer.scalar(
                select(func.count()).select_from(Role).where(Role.id == row_id)
            )

    def guard(current):
        if not claim_conflict_savepoint_commit(current, expected_root=root):
            raise RuntimeError("participant completion forbidden")

    def reenter(current, *_args):
        state = current_conflict_savepoint(current)
        if (
            state is None
            or state.phase is not ConflictSavepointPhase.RELEASE
            or attempts
        ):
            return
        attempts.append(True)
        try:
            if root_direct:
                root.commit()
            else:
                current.commit()
        except (RuntimeError, SQLAlchemyError) as exc:
            denied.append(exc)
            if not swallow:
                raise
        else:
            pytest.fail("reentrant completion succeeded")

    listeners = (
        [(event_name, reenter), ("before_commit", guard)]
        if listener_first
        else [("before_commit", guard), (event_name, reenter)]
    )
    for name, listener in listeners:
        event.listen(db, name, listener)
    try:
        try:
            with conflict_savepoint(db):
                db.add(
                    Role(
                        id=row_id,
                        tenant_id=tenant_id,
                        slug=f"conflict-{row_id.hex}",
                        name="Uncommitted participant",
                    )
                )
                # Deliberately defer flush until release, exercising both
                # before_commit and release-time before_flush listeners.
        except (RuntimeError, SQLAlchemyError) as exc:
            completion_errors.append(exc)
        assert attempts == [True] and denied
        if not swallow:
            assert completion_errors
        assert db.get_transaction() is root and root.is_active
        assert current_conflict_savepoint(db) is None
        assert not claim_conflict_savepoint_commit(db, expected_root=root)
        assert observe_count() == 0, "writer committed before owner completion"

        # A swallowed failed call may permit legitimate savepoint release.
        # Force a later owner failure and prove all staged work is discardable.
        with pytest.raises(ValueError, match="owner failure"):
            try:
                raise ValueError("forced owner failure")
            finally:
                db.rollback()
        assert observe_count() == 0, "writer effects survived owner rollback"
    finally:
        for name, listener in reversed(listeners):
            event.remove(db, name, listener)
        db.rollback()
        assert not conflict_savepoint_requires_rollback(db, expected_root=root)
        with admin_engine.begin() as cleanup:
            cleanup.execute(delete(Role).where(Role.id == row_id))


@pytest.mark.parametrize("failure_event", ["after_commit", "after_transaction_end"])
def test_real_postgres_release_completion_failure_retains_owner_rollback(
    admin_session, admin_engine, tenant_a, failure_event
):
    db = admin_session
    tenant_id = tenant_a.id
    row_id = uuid4()
    db.connection()
    root = db.get_transaction()
    failure = ValueError(f"{failure_event} failed")
    guard_roots = [root]
    targets = []
    fired = []

    def observe_count():
        with admin_engine.connect() as observer:
            return observer.scalar(
                select(func.count()).select_from(Role).where(Role.id == row_id)
            )

    def guard(current):
        if not claim_conflict_savepoint_commit(current, expected_root=guard_roots[0]):
            raise RuntimeError("participant completion forbidden")

    def fail(current, transaction=None):
        if not targets or fired:
            return
        if failure_event == "after_transaction_end" and transaction is not targets[0]:
            return
        state = current_conflict_savepoint(current)
        if state is None or state.savepoint is not targets[0]:
            return
        fired.append(state.savepoint)
        assert state.phase is ConflictSavepointPhase.RELEASE
        assert not state.savepoint.is_active
        raise failure

    event.listen(db, "before_commit", guard)
    event.listen(db, failure_event, fail)
    try:
        with pytest.raises(ValueError) as caught:
            with conflict_savepoint(db):
                targets.append(current_conflict_savepoint(db).savepoint)
                db.add(
                    Role(
                        id=row_id,
                        tenant_id=tenant_id,
                        slug=f"conflict-{row_id.hex}",
                        name="Released child",
                    )
                )
        assert caught.value is failure
        assert fired == targets
        assert db.get_transaction() is root and root.is_active
        assert db.get_nested_transaction() is None
        assert current_conflict_savepoint(db) is None
        assert not claim_conflict_savepoint_commit(db, expected_root=root)
        assert conflict_savepoint_requires_rollback(db, expected_root=root)
        for complete in (db.commit, root.commit):
            with pytest.raises(ConflictSavepointProtocolError, match="must roll back"):
                complete()
            assert db.get_transaction() is root and root.is_active
            assert observe_count() == 0
        assert db.scalar(select(Role.name).where(Role.id == row_id)) == "Released child"
        assert observe_count() == 0
        db.rollback()
        assert not conflict_savepoint_requires_rollback(db, expected_root=root)
        assert observe_count() == 0
        db.connection()
        fresh_root = db.get_transaction()
        assert fresh_root is not root
        guard_roots[0] = fresh_root
        with conflict_savepoint(db):
            db.add(
                Role(
                    id=row_id,
                    tenant_id=tenant_id,
                    slug=f"conflict-{row_id.hex}",
                    name="Fresh root",
                )
            )
        assert not conflict_savepoint_requires_rollback(db, expected_root=fresh_root)
        assert db.scalar(select(Role.name).where(Role.id == row_id)) == "Fresh root"
        assert observe_count() == 0
    finally:
        event.remove(db, failure_event, fail)
        event.remove(db, "before_commit", guard)
        db.rollback()
        with admin_engine.begin() as cleanup:
            cleanup.execute(delete(Role).where(Role.id == row_id))
